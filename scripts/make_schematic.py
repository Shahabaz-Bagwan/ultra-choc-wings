def symbol_def(name, prefix=""):
    pins, graphics, descr, hide_names = SYMBOLS[name]
    ref = {"Q_NMOS_GSD": "Q", "SW_Push": "SW", "SW_SPDT": "T", "Battery_Cell": "BT", "Pad": "PAD",
           "MountingHole": "H", "XIAO_nRF52840": "U", "D_Schottky": "D", "LED": "L"}.get(name, name[0])
    top = max([y for _, _, _, y, _, _ in pins] + [2]) + 1.27
    out = [f'(symbol "{prefix}{name}"' + (" (pin_names (offset 0) hide)" if hide_names else " (pin_names (offset 1.016))")
           + (" (in_bom no) (on_board yes)" if not pins else " (in_bom yes) (on_board yes)"),
           f'  (property "Reference" "{ref}" (at 0 {top + 1.27} 0) {FONT})',
           f'  (property "Value" "{name}" (at 0 {-top - 1.27} 0) {FONT})',
           f'  (property "Footprint" "" (at 0 0 0) {FONT_HIDE})',
           f'  (property "Datasheet" "~" (at 0 0 0) {FONT_HIDE})',
           f'  (property "ki_description" "{descr}" (at 0 0 0) {FONT_HIDE})',
           f'  (symbol "{name}_0_1" ' + " ".join(graphics) + ")"]
    pin_s = " ".join(
        f'(pin passive line (at {x} {y} {a}) (length {ln}) (name "{nm}" {FONT}) (number "{n}" {FONT}))'
        for n, nm, x, y, a, ln in pins)
    out.append(f'  (symbol "{name}_1_1" {pin_s})')
    return "\n".join(out) + ")"


# --- board ------------------------------------------------------------------

def parts(board):
    """Board footprints as dicts, sorted by reference."""
    out = []
    for fp in board.GetFootprints():
        nets = {}
        for pad in fp.Pads():
            if pad.GetNumber() and pad.GetNetname():
                nets[pad.GetNumber()] = pad.GetNetname()
        value = "XIAO nRF52840" if fp.GetReference().startswith("xiao") else value_of(fp)
        out.append({"ref": fp.GetReference(), "value": value,
                    "fp": str(fp.GetFPID().GetUniStringLibItemName()).split(":")[-1], "nets": nets, "obj": fp})
    key = lambda p: (re.sub(r"\d+$", "", p["ref"]), int(re.search(r"(\d*)$", p["ref"]).group(1) or 0))
    return sorted(out, key=key)


def export_footprints(board, libdir):
    os.makedirs(libdir, exist_ok=True)
    done = set()
    for fp in board.GetFootprints():
        name = str(fp.GetFPID().GetUniStringLibItemName()).split(":")[-1]
        if name in done:
            continue
        done.add(name)
        copy = pcbnew.FOOTPRINT(fp)
        if copy.IsFlipped():
            copy.Flip(copy.GetPosition(), False)
        copy.SetOrientationDegrees(0)
        copy.SetPosition(pcbnew.VECTOR2I(0, 0))
        for pad in copy.Pads():
            pad.SetNetCode(0)
        copy.SetReference("REF**")
        copy.SetFPID(pcbnew.LIB_ID("", name))
        path = os.path.join(libdir, name + ".kicad_mod")
        if os.path.exists(path):
            os.remove(path)
        pcbnew.FootprintSave(libdir, copy)
    return sorted(done)


# --- schematic --------------------------------------------------------------

def label_angle(pin_angle):
    return {0: 180, 180: 0, 270: 90, 90: 270}[pin_angle]


def gl(net, X, Y, angle, key):
    """Global label, so the net name is exactly the board's (a local label on
    the root sheet would become "/NAME")."""
    just = "left" if angle in (0, 90) else "right"
    return (f'(global_label "{net}" (shape passive) (at {X} {Y} {angle}) (fields_autoplaced) '
            f'(effects (font (size 1.27 1.27)) (justify {just})) (uuid {uid("label", *key)})\n'
            f'  (property "Intersheetrefs" "${{INTERSHEET_REFS}}" (at {X} {Y} 0) {FONT_HIDE}))')


def wire(a, b, key, items):
    items.append(f'(wire (pts (xy {a[0]} {a[1]}) (xy {b[0]} {b[1]})) (stroke (width 0) (type default)) '
                 f'(uuid {uid("wire", *key)}))')


def pin_xy(sym, n, x, y, rot=0):
    """Schematic position of pin `n` of a symbol placed at (x, y), rot 0 or 180."""
    for num, _, px, py, a, _ in SYMBOLS[sym][0]:
        if num == n:
            return (round(x + px, 2), round(y - py, 2)) if rot == 0 else (round(x - px, 2), round(y + py, 2))
    raise KeyError(n)


def place(sym, ref, value, fp_name, x, y, nets, lcsc, items, instances, rot=0, wired=()):
    """Place a symbol. Pins in `wired` get no label of their own: the caller
    draws a wire to the part they connect to and names that wire."""
    pins = SYMBOLS[sym][0]
    u = uid("sym", ref)
    props = [f'(property "Reference" "{ref}" (at {x} {y - 3.81 - (7.62 if sym == "XIAO_nRF52840" else 0)} 0) {FONT})',
             f'(property "Value" "{value}" (at {x} {y + 3.81 + (7.62 if sym == "XIAO_nRF52840" else 0)} 0) {FONT})',
             f'(property "Footprint" "{LIB}:{fp_name}" (at {x} {y} 0) {FONT_HIDE})',
             f'(property "Datasheet" "~" (at {x} {y} 0) {FONT_HIDE})']
    if lcsc:
        props.append(f'(property "LCSC" "{lcsc}" (at {x} {y} 0) {FONT_HIDE})')
    pin_uuids = " ".join(f'(pin "{n}" (uuid {uid("pin", ref, n)}))' for n, *_ in pins)
    items.append(f'(symbol (lib_id "{LIB}:{sym}") (at {x} {y} {rot}) (unit 1) (in_bom {"no" if not pins else "yes"}) '
                 f'(on_board yes) (dnp no) (uuid {u})\n  ' + "\n  ".join(props) + f"\n  {pin_uuids}\n"
                 f'  (instances (project "{PROJECT}" (path "/{ROOT}" (reference "{ref}") (unit 1)))))')
    for n, _, px, py, a, _ in pins:
        X, Y = pin_xy(sym, n, x, y, rot)
        net = nets.get(n)
        if net is None:
            items.append(f"(no_connect (at {X} {Y}) (uuid {uid('nc', ref, n)}))")
            continue
        if n in wired:
            continue
        items.append(gl(net, X, Y, label_angle((a + rot) % 360), (ref, n)))
    instances[ref] = u


def text(s, x, y, size=2.54):
    s = s.replace('"', '\\"')
    return (f'(text "{s}" (at {x} {y} 0) (effects (font (size {size} {size})) (justify left bottom)) '
            f'(uuid {uid("text", s)}))')


def g(v):
    """Snap to the 1.27 mm schematic grid."""
    return round(round(v / 1.27) * 1.27, 2)


def symbol_for(p):
    if p["value"] == "B5819W":
        return "D_Schottky"
    return SYMBOL_OF[p["fp"]]


def lcsc_for(p):
    part = PARTS.get(p["value"])
    return part[2] if part else ""


def write_schematic(plist, path):
    by_ref = {p["ref"]: p for p in plist}
    items, instances, placed = [], {}, set()

    def put(p, x, y, rot=0, wired=()):
        place(symbol_for(p), p["ref"], p["value"] or SYMBOL_OF[p["fp"]], p["fp"], g(x), g(y), p["nets"],
              lcsc_for(p), items, instances, rot, wired)
        placed.add(p["ref"])

    def link(a, pa, b, pb, ra=0, rb=0, angle=90):
        """Wire pin `pa` of part a to pin `pb` of part b and name the wire after
        the net they share, with a label standing on the wire."""
        (sa, xa, ya), (sb, xb, yb) = pos[a["ref"]], pos[b["ref"]]
        p1, p2 = pin_xy(sa, pa, xa, ya, ra), pin_xy(sb, pb, xb, yb, rb)
        assert a["nets"][pa] == b["nets"][pb], (a["ref"], pa, b["ref"], pb)
        key = (a["ref"], pa, b["ref"], pb)
        wire(p1, p2, key, items)
        mid = (round((p1[0] + p2[0]) / 2, 2), round((p1[1] + p2[1]) / 2, 2))
        items.append(gl(a["nets"][pa], mid[0], mid[1], angle, key))

    pos = {}

    def put_at(p, x, y, rot=0, wired=()):
        x, y = g(x), g(y)
        pos[p["ref"]] = (symbol_for(p), x, y)
        put(p, x, y, rot, wired)

    # Key matrix, one block per key. Each key is two chains, wired where two
    # parts share a net and labelled at the ends where the net goes elsewhere:
    #   row label - diode - SW - column label        (switch to its diode)
    #   LED_K label - LED - resistor - VCC3 label    (LED to its resistor)
    items.append(text("Key matrix (COL2ROW): switch, diode, per-key LED and its resistor", 25.4, 35.56, 3))
    keys = [p for p in plist if p["ref"].startswith("SW")]
    for i, sw in enumerate(keys):
        n = sw["ref"][2:]
        bx, by = 25.4 + (i % 6) * 91.44, 50.8 + (i // 6) * 63.5
        row = {r: by_ref[f"{r}{n}"] for r in ("D", "SW", "L", "R") if f"{r}{n}" in by_ref}
        d, s_, l, r = row.get("D"), row.get("SW"), row.get("L"), row.get("R")
        put_at(d, bx + 22.86, by + 5.08, 0, wired=("2",))
        put_at(s_, bx + 43.18, by + 5.08, 0, wired=("1",))
        link(d, "2", s_, "1", 0, 0, 90)
        put_at(l, bx + 22.86, by + 30.48, 0, wired=("2",))
        put_at(r, bx + 43.18, by + 30.48, 180, wired=("2",))
        link(l, "2", r, "2", 0, 180, 270)

    y0 = 254.0
    items.append(text("MCU: Seeed XIAO nRF52840 (flippable footprint)", 25.4, y0, 3))
    for p in plist:
        if p["fp"] == "xiao-ble":
            put_at(p, 76.2, y0 + 30.48)

    x0 = 172.72
    items.append(text("Power: CR2032 -> slide switch -> B5819W -> RAW, 2x 22uF on RAW", x0, y0, 3))
    items.append(text("Wire the RAW pad (PAD1) to the BAT+ pad under the XIAO.", x0, y0 + 5.08, 1.8))
    kind = {symbol_for(p): p for p in plist if symbol_for(p) in ("Battery_Cell", "SW_SPDT", "D_Schottky")}
    bt, sw, sd = kind["Battery_Cell"], kind["SW_SPDT"], kind["D_Schottky"]
    yp = y0 + 22.86
    # BT1 + -> slide switch (pin 1) ; common (pin 2) -> B5819W anode ; cathode = RAW
    put_at(bt, x0 + 20.32, yp, 180, wired=("1",))
    put_at(sw, x0 + 50.8, yp - 2.54, 180, wired=("1", "2"))
    put_at(sd, x0 + 76.2, yp - 2.54, 180, wired=("2",))
    link(bt, "1", sw, "1", 180, 180, 90)
    link(sw, "2", sd, "2", 180, 180, 90)
    for i, p in enumerate(q for q in plist if symbol_for(q) in ("C", "Pad")):
        put_at(p, x0 + 106.68 + i * 25.4, yp)

    items.append(text("LED driver: all LED cathodes switched to GND, PWM on D6, 100k pull-down", x0, y0 + 50.8, 3))
    q1 = next(p for p in plist if p["ref"].startswith("Q"))
    pd = by_ref["R19"]
    put_at(pd, x0 + 20.32, y0 + 73.66, 180, wired=("1",))
    put_at(q1, x0 + 45.72, y0 + 73.66, 0, wired=("1",))
    link(pd, "1", q1, "1", 180, 0, 90)

    items.append(text("Mounting holes", x0 + 203.2, y0 + 50.8, 3))
    rest = [p for p in plist if p["ref"] not in placed]
    for i, p in enumerate(rest):
        put_at(p, x0 + 213.36 + i * 20.32, y0 + 73.66)

    used = sorted({symbol_for(p) for p in plist})
    lib_symbols = "\n".join(symbol_def(s, LIB + ":") for s in used)
    sch = f"""(kicad_sch (version 20230121) (generator eeschema)
  (uuid {ROOT})
  (paper "A2")
  (title_block
    (title "Ultra Choc Wings, one half")
    (comment 1 "Generated from the routed board by scripts/make_schematic.py; rerun scripts/build_pcb.sh")
    (comment 2 "Reversible PCB: left half has parts on F, right half on B")
  )
  (lib_symbols
{lib_symbols}
  )
{chr(10).join(items)}
  (sheet_instances (path "/" (page "1")))
)
"""
    with open(path, "w") as f:
        f.write(sch)
    return instances


def write_symbol_lib(path):
    body = "\n".join(symbol_def(s) for s in sorted(SYMBOLS))
    with open(path, "w") as f:
        f.write(f"(kicad_symbol_lib (version 20220914) (generator kicad_symbol_editor)\n{body}\n)\n")


def write_lib_tables(outdir):
    with open(os.path.join(outdir, "fp-lib-table"), "w") as f:
        f.write(f'(fp_lib_table\n  (version 7)\n  (lib (name "{LIB}")(type "KiCad")(uri "${{KIPRJMOD}}/{LIB}.pretty")'
                f'(options "")(descr "Footprints of every part on the board"))\n)\n')
    with open(os.path.join(outdir, "sym-lib-table"), "w") as f:
        f.write(f'(sym_lib_table\n  (version 7)\n  (lib (name "{LIB}")(type "KiCad")(uri "${{KIPRJMOD}}/{LIB}.kicad_sym")'
                f'(options "")(descr "Symbols of every part on the board"))\n)\n')


# --- linking the board ------------------------------------------------------

def link_board(pcb_path, instances):
    """Point each footprint at its library footprint and schematic symbol.

    Works on the board file's text, so it handles any KiCad version's file."""
    src = open(pcb_path).read()
    # KiCad 8 and newer also write the sheet name and file next to the path.
    version = re.search(r"\(version (\d+)\)", src)
    sheet = bool(version) and int(version.group(1)) >= 20240108
    out, i = [], 0
    for m in re.finditer(r'\(footprint "([^"]+)"', src):
        if m.start() < i:
            continue
        depth, j = 0, m.start()
        while True:
            c = src[j]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            elif c == '"':
                j += 1
                while src[j] != '"':
                    j += 2 if src[j] == "\\" else 1
            j += 1
        block = src[m.start():j + 1]
        ref = re.search(r'\((?:property "Reference"|fp_text reference) "([^"]+)"', block)
        name = m.group(1).split(":")[-1]
        block = block.replace(m.group(0), f'(footprint "{LIB}:{name}"', 1)
        if ref and ref.group(1) in instances:
            block = re.sub(r'\n[ \t]*\((?:path|sheetname|sheetfile) "[^"]*"\)', "", block)
            nl = re.search(r"\n([ \t]*)\(", block)
            indent = nl.group(1) if nl else " "
            link = f'\n{indent}(path "/{instances[ref.group(1)]}")'
            if sheet:
                link += f'\n{indent}(sheetname "/")\n{indent}(sheetfile "{PROJECT}.kicad_sch")'
            # KiCad writes these just before (attr ...); fall back to the end of the header.
            attr = re.search(r"\n" + re.escape(indent) + r"\(attr\b", block)
            at = re.search(r"\n" + re.escape(indent) + r"\(at [^\n]*", block)
            head = attr.start() if attr else (at.end() if at else block.index("\n"))
            block = block[:head] + link + block[head:]
        out.append(src[i:m.start()])
        out.append(block)
        i = j + 1
    out.append(src[i:])
    with open(pcb_path, "w") as f:
        f.write("".join(out))


def main():
    pcb_path = sys.argv[1]
    link_path = sys.argv[2] if len(sys.argv) > 2 else pcb_path
    outdir = os.path.dirname(os.path.abspath(link_path))
    board = pcbnew.LoadBoard(pcb_path)
    plist = parts(board)
    fps = export_footprints(board, os.path.join(outdir, LIB + ".pretty"))
    write_symbol_lib(os.path.join(outdir, LIB + ".kicad_sym"))
    instances = write_schematic(plist, os.path.join(outdir, PROJECT + ".kicad_sch"))
    write_lib_tables(outdir)
    del board
    link_board(link_path, instances)
