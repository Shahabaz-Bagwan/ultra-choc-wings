#!/usr/bin/env python3
"""Write the KiCad schematic and libraries that match the routed board.

    python3 scripts/make_schematic.py pcb/ultra-choc-wings.kicad_pcb [board_to_link.kicad_pcb]

By default the board is both read and linked. If KiCad's python module is too
old to open the board (it was saved by a newer KiCad), read an older copy of
the same board and name the real one as the second argument: the files are
written next to it and its footprints are linked by editing its text.

The board is generated by ergogen, so it has no schematic of its own. This
reads every footprint and pad net from the board and writes, next to it:

  ucw.pretty/                  one footprint per part type, taken from the board
  ucw.kicad_sym                one symbol per part type
  ultra-choc-wings.kicad_sch   every part with its nets (as net labels)
  fp-lib-table, sym-lib-table  so the project finds both libraries

It then points each footprint on the board at its library footprint and at
its schematic symbol, so "Update PCB from Schematic" and cross-probing match
part for part. Symbol UUIDs come from the reference designator, so rerunning
this after a reroute gives the same files.
"""
