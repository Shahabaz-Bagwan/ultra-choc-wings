def two_pin(graphics, length=2.54):
    return [("1", "~", -5.08, 0, 0, length), ("2", "~", 5.08, 0, 180, length)], graphics


def poly(*pts, fill="none"):
    xy = " ".join(f"(xy {x} {y})" for x, y in pts)
    return f"(polyline (pts {xy}) (stroke (width 0.254) (type default)) (fill (type {fill})))"


def circle(x, y, r, fill="none"):
    return f"(circle (center {x} {y}) (radius {r}) (stroke (width 0.254) (type default)) (fill (type {fill})))"


def rect(x0, y0, x1, y1, fill="none"):
    return f"(rectangle (start {x0} {y0}) (end {x1} {y1}) (stroke (width 0.254) (type default)) (fill (type {fill})))"


